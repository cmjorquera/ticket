            <h5>📌 ¿Qué es la Ley Karin?</h5>
            <p>La Ley Karin es una legislación chilena creada para proteger a los trabajadores del acoso laboral...</p>

            <h5>⚠️ ¿Qué Constituye Acoso Laboral?</h5>
            <ul>
                <li><strong>Acoso Verbal:</strong> Insultos, amenazas, o comentarios despectivos.</li>
                <li><strong>Acoso Físico:</strong> Contacto físico no deseado o intimidatorio.</li>
                <li><strong>Acoso Psicológico:</strong> Hostigamiento, intimidación o manipulación emocional.</li>
                <li><strong>Acoso Sexual:</strong> Comentarios inapropiados, gestos ofensivos o insinuaciones sexuales no deseadas.</li>
            </ul>

            <h5>📋 Procedimiento para Denunciar el Acoso Laboral:</h5>
            <ol>
                <li><strong>Recolección de Evidencia:</strong> Antes de presentar una denuncia, recopila toda la evidencia posible...</li>
                <li><strong>Reportar Internamente:</strong> La mayoría de las empresas tienen procedimientos internos...</li>
                <li><strong>Presentar la Denuncia Formal:</strong> Si los canales internos no resuelven el problema, puedes presentar una denuncia formal...</li>
                <li><strong>Protegerse de Represalias:</strong> La Ley Karin prohíbe represalias contra denunciantes...</li>
            </ol>

            <h5>✅ Conclusión</h5>
            <p>Denunciar acoso laboral es un derecho crucial para mantener un entorno laboral seguro...</p>

